package com.racsai.backend.entity;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

@Entity
@Table(name = "users")
@Getter
@Setter
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "user_id", length = 36, updatable = false, nullable = false)
    private String userId;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "workspace_id", nullable = false, foreignKey = @ForeignKey(name = "fk_users_workspace"))
    @JsonIgnoreProperties({"hibernateLazyInitializer", "handler"})
    private Workspace workspace;

    @Column(name = "full_name", length = 100, nullable = false)
    private String fullName;

    @Column(name = "email", length = 100, nullable = false, unique = true)
    private String email;

    @JsonProperty(access = JsonProperty.Access.WRITE_ONLY)
    @Column(name = "password_hash", length = 255, nullable = false)
    private String passwordHash;

    @Column(name = "role", length = 50, nullable = false)
    private String role;

    @Column(name = "access_status", length = 20, nullable = false)
    private String accessStatus = "Active";

    @OneToMany(mappedBy = "createdBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<Invitation> invitations = new ArrayList<>();

    @OneToMany(mappedBy = "user", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<LoginSession> loginSessions = new ArrayList<>();

    @OneToMany(mappedBy = "user", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<PasswordReset> passwordResets = new ArrayList<>();

    // ADDED: Cascade deletes for Job Postings authored by this user
    @OneToMany(mappedBy = "createdBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<JobPosting> jobPostings = new ArrayList<>();

    // ADDED: Cascade deletes for Candidates uploaded by this user (TA/Admin)
    @OneToMany(mappedBy = "uploadedBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<Candidate> candidates = new ArrayList<>();

    // ADDED: Cascade deletes for Candidate Status History audit logs created by this user
    @OneToMany(mappedBy = "changedBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<CandidateStatusHistory> statusHistories = new ArrayList<>();

    // ADDED: Cascade deletes for Interview Checklists generated by this user (HM/TA)
    @OneToMany(mappedBy = "generatedBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<InterviewChecklist> interviewChecklists = new ArrayList<>();

    // ADDED: Cascade deletes for HR Handoff Reports approved by this hiring manager
    @OneToMany(mappedBy = "hiringManager", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<HrHandoffReport> hrHandoffReports = new ArrayList<>();

    // ADDED: Cascade deletes for Engagement Sequences created by this user
    @OneToMany(mappedBy = "createdBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<EngagementSequence> engagementSequences = new ArrayList<>();

    // ADDED: Cascade deletes for Data Export History logs generated by this user
    @OneToMany(mappedBy = "generatedBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<DataExportHistory> dataExportHistories = new ArrayList<>();

    // ADDED: Cascade deletes for API Key configurations set up by this System Admin
    @OneToMany(mappedBy = "configuredBy", cascade = CascadeType.ALL, orphanRemoval = true)
    @JsonIgnore
    private List<TenantApiKey> configuredApiKeys = new ArrayList<>();

    @CreationTimestamp
    @Column(name = "created_at", updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;
}